const byId = new Map(products.map((p) => [p.id, p]))

export function getProductById(id: string): Product | undefined {
    return byId.get(id)
}

export function getProducts(filter: { category?: Category; region?: Region } = {}): Product[] {
    return products.filter(
        (p) => (!filter.category || p.category === filter.category) && (!filter.region || p.region === filter.region),
    )
}

export function getRelatedProducts(product: Product, limit = 4): Product[] {
    const sameGroup = products.filter(
        (p) =>
            p.id !== product.id &&
            p.inStock &&
            p.category === product.category &&
            (product.region ? p.region === product.region : p.line === product.line),
    )
    const rest = products.filter((p) => p.id !== product.id && p.inStock && p.category === product.category && !sameGroup.includes(p))
    return [...sameGroup, ...rest].slice(0, limit)
}

export function priceRange(list: Product[]) {
    const prices = list.map((p) => p.price)
    return { min: Math.min(...prices), max: Math.max(...prices) }
}
